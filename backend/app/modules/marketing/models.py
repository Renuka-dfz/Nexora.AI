# DIMENSION 3: SOCIAL ACCOUNT
# ============================================================

class DimSocialAccount(Base):
    """
    Stores connected LinkedIn and Instagram accounts.

    OAuth credentials must be stored separately and securely.
    """

    __tablename__ = "dim_social_account"

    __table_args__ = (
        UniqueConstraint(
            "social_account_id",
            "company_id",
            name="uq_marketing_account_company",
        ),
        UniqueConstraint(
            "platform",
            "external_account_id",
            name="uq_marketing_platform_external_account",
        ),
        CheckConstraint(
            "platform IN ('linkedin', 'instagram')",
            name="ck_marketing_account_platform",
        ),
        CheckConstraint(
            "connection_status IN "
            "('connected', 'disconnected', 'expired')",
            name="ck_marketing_account_connection_status",
        ),
    )

    social_account_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    company_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey(
            "dim_company.company_id",
            ondelete="RESTRICT",
        ),
        nullable=False,
        index=True,
    )

    platform: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
    )

    external_account_id: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
    )

    account_name: Mapped[Optional[str]] = mapped_column(
        String(200),
        nullable=True,
    )

    account_handle: Mapped[Optional[str]] = mapped_column(
        String(200),
        nullable=True,
    )

    account_type: Mapped[Optional[str]] = mapped_column(
        String(50),
        nullable=True,
    )

    connection_status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        server_default=text("'disconnected'"),
    )

    connected_at: Mapped[Optional[datetime]] = mapped_column(
        TIMESTAMP(timezone=True),
        nullable=True,
    )


