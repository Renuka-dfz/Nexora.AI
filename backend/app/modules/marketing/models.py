class DimDate(Base):
    """
    Stores calendar information for marketing analytics.

    Example:
        date_id: 20261111
        full_date: 2026-11-11
        month_name: November
        year: 2026
    """

    __tablename__ = "dim_date"

    __table_args__ = (
        CheckConstraint(
            "day_of_month BETWEEN 1 AND 31",
            name="ck_marketing_date_day",
        ),
        CheckConstraint(
            "month_number BETWEEN 1 AND 12",
            name="ck_marketing_date_month",
        ),
        CheckConstraint(
            "quarter BETWEEN 1 AND 4",
            name="ck_marketing_date_quarter",
        ),
    )

    date_id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
    )

    full_date: Mapped[date] = mapped_column(
        Date,
        nullable=False,
        unique=True,
    )

    day_of_week: Mapped[str] = mapped_column(
        String(15),
        nullable=False,
    )

    day_of_month: Mapped[int] = mapped_column(
        SmallInteger,
        nullable=False,
    )

    month_number: Mapped[int] = mapped_column(
        SmallInteger,
        nullable=False,
    )

    month_name: Mapped[str] = mapped_column(
        String(15),
        nullable=False,
    )

    quarter: Mapped[int] = mapped_column(
        SmallInteger,
        nullable=False,
    )

    year: Mapped[int] = mapped_column(
        SmallInteger,
        nullable=False,
    )

    is_weekend: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
    )


