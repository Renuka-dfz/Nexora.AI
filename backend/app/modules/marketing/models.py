# DIMENSION 2: CONTENT
# ============================================================

class DimContent(Base):
    """
    Stores marketing content generated by AI or created manually.

    Example:
        Company: DataFactZ
        Content: Future of Generative AI
        Platform: LinkedIn
        Approval Status: approved
    """

    __tablename__ = "dim_content"

    __table_args__ = (
        UniqueConstraint(
            "content_id",
            "company_id",
            name="uq_marketing_content_company",
        ),
        CheckConstraint(
            "approval_status IN "
            "('draft', 'pending', 'approved', 'rejected')",
            name="ck_marketing_content_approval_status",
        ),
        CheckConstraint(
            "generation_type IN ('ai', 'manual')",
            name="ck_marketing_content_generation_type",
        ),
    )

    content_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    company_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey(
            "dim_company.company_id",
            ondelete="RESTRICT",
        ),
        nullable=False,
        index=True,
    )

    content_title: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
    )

    content_type: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
    )

    platform_target: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
    )

    topic: Mapped[Optional[str]] = mapped_column(
        String(255),
        nullable=True,
    )

    content_text: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    tone: Mapped[Optional[str]] = mapped_column(
        String(50),
        nullable=True,
    )

    generation_type: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        server_default=text("'ai'"),
    )

    approval_status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        server_default=text("'draft'"),
    )

    created_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True),
        nullable=False,
        server_default=func.now(),
    )


