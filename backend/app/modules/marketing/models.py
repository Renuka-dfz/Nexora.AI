# FACT TABLE: MARKETING PERFORMANCE
# ============================================================

class FactMarketingPerformance(Base):
    """
    Stores the performance of published marketing content.

    Fact grain:
        One published post + metric period + collection timestamp.

    Example:
        LinkedIn post:
            impressions = 5000
            likes = 200
            comments = 30
            shares = 15

    Metrics represent platform-reported snapshots.
    Cumulative snapshots must not be summed across dates.
    """

    __tablename__ = "fact_marketing_performance"

    __table_args__ = (

        # Ensure content belongs to the same company.
        ForeignKeyConstraint(
            ["content_id", "company_id"],
            ["dim_content.content_id", "dim_content.company_id"],
            name="fk_marketing_performance_content_company",
            ondelete="RESTRICT",
        ),

        # Ensure social account belongs to the same company.
        ForeignKeyConstraint(
            ["social_account_id", "company_id"],
            [
                "dim_social_account.social_account_id",
                "dim_social_account.company_id",
            ],
            name="fk_marketing_performance_account_company",
            ondelete="RESTRICT",
        ),

        # Prevent duplicate metric snapshots.
        UniqueConstraint(
            "published_post_id",
            "metric_period",
            "collected_at",
            name="uq_marketing_post_metric_snapshot",
        ),

        # Prevent negative performance values.
        CheckConstraint(
            "impressions >= 0",
            name="ck_marketing_impressions",
        ),
        CheckConstraint(
            "reach >= 0",
            name="ck_marketing_reach",
        ),
        CheckConstraint(
            "likes >= 0",
            name="ck_marketing_likes",
        ),
        CheckConstraint(
            "comments >= 0",
            name="ck_marketing_comments",
        ),
        CheckConstraint(
            "shares >= 0",
            name="ck_marketing_shares",
        ),
        CheckConstraint(
            "saves >= 0",
            name="ck_marketing_saves",
        ),
        CheckConstraint(
            "clicks >= 0",
            name="ck_marketing_clicks",
        ),
        CheckConstraint(
            "video_views >= 0",
            name="ck_marketing_video_views",
        ),

        CheckConstraint(
            "metric_period IN ('lifetime', 'daily')",
            name="ck_marketing_metric_period",
        ),

        CheckConstraint(
            "retrieval_status IN ('success', 'partial', 'failed')",
            name="ck_marketing_retrieval_status",
        ),

        # Indexes for reporting queries.
        Index(
            "ix_marketing_performance_company_date",
            "company_id",
            "date_id",
        ),
        Index(
            "ix_marketing_performance_content",
            "content_id",
        ),
        Index(
            "ix_marketing_performance_account",
            "social_account_id",
        ),
        Index(
            "ix_marketing_performance_published_post",
            "published_post_id",
        ),
    )

    performance_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    company_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey(
            "dim_company.company_id",
            ondelete="RESTRICT",
        ),
        nullable=False,
    )

    content_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
    )

    social_account_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
    )

    date_id: Mapped[int] = mapped_column(
        Integer,
        ForeignKey(
            "dim_date.date_id",
            ondelete="RESTRICT",
        ),
        nullable=False,
    )

    # Reference to a published post.
    # Can be linked to the publication model later.
    published_post_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
    )

    collected_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True),
        nullable=False,
    )

    impressions: Mapped[Optional[int]] = mapped_column(
        BigInteger,
        nullable=True,
    )

    reach: Mapped[Optional[int]] = mapped_column(
        BigInteger,
        nullable=True,
    )

    likes: Mapped[Optional[int]] = mapped_column(
        BigInteger,
        nullable=True,
    )

    comments: Mapped[Optional[int]] = mapped_column(
        BigInteger,
        nullable=True,
    )

    shares: Mapped[Optional[int]] = mapped_column(
        BigInteger,
        nullable=True,
    )

    saves: Mapped[Optional[int]] = mapped_column(
        BigInteger,
        nullable=True,
    )

    clicks: Mapped[Optional[int]] = mapped_column(
        BigInteger,
        nullable=True,
    )

    video_views: Mapped[Optional[int]] = mapped_column(
        BigInteger,
        nullable=True,
    )

    metric_period: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        server_default=text("'lifetime'"),
    )

    metric_source: Mapped[Optional[str]] = mapped_column(
        String(30),
        nullable=True,
    )

    retrieval_status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        server_default=text("'success'"),
    )

    created_at: Mapped[datetime] = mapped_column(
        TIMESTAMP(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
