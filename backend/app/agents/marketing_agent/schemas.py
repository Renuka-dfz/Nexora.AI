"""
Nexora.AI - Marketing Agent Pydantic Schemas & API Contracts.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from app.modules.marketing.schemas import (
    ALLOWED_APPROVAL_STATUSES,
    ALLOWED_GENERATION_TYPES,
    ApprovalStatus,
    GenerationType,
)

PlatformType = Literal["linkedin", "instagram", "article"]
PublishStatus = Literal["draft", "pending", "approved", "scheduled", "published", "failed"]


class MarketingRequest(BaseModel):
    """Initial request payload to trigger the Marketing Agent."""
    company_id: UUID
    platform: PlatformType = "linkedin"
    topic: str = Field(min_length=3, max_length=500)
    tone: str | None = Field(default="authoritative yet accessible", max_length=100)
    target_audience: str | None = Field(default=None, max_length=200)
    instructions: str | None = Field(default=None, max_length=1000)


class ContentOutline(BaseModel):
    """Structured outline before generating full post/article copy."""
    title: str | None = None
    hook: str
    key_sections: list[str] = Field(default_factory=list)
    call_to_action: str
    target_audience: str | None = None


class MarketingDraftOutput(BaseModel):
    """Complete grounded marketing copy generated by the local LLM."""
    model_config = ConfigDict(from_attributes=True)

    title: str | None = None
    hook: str
    body: str
    call_to_action: str
    hashtags: list[str] = Field(default_factory=list)
    sources: list[str] = Field(default_factory=list)
    caption: str | None = None
    description: str | None = None
    seo_keywords: list[str] = Field(default_factory=list)
    visual_headline: str | None = None
    visual_subhead: str | None = None
    pillars: list[str] = Field(default_factory=list)
    metric_highlight: str | None = None
    storyboard_scenes: list[dict[str, Any]] = Field(default_factory=list)
    status: ApprovalStatus = "draft"


class ValidationFinding(BaseModel):
    """Individual rule check result during factual & safety verification."""
    check_name: str
    passed: bool
    details: str
    severity: Literal["low", "medium", "critical"] = "low"


class MarketingValidationReport(BaseModel):
    """Consolidated safety and factual verification report."""
    passed: bool
    factual_grounding_score: float = Field(ge=0.0, le=1.0)
    findings: list[ValidationFinding] = Field(default_factory=list)
    unsupported_claims: list[str] = Field(default_factory=list)


class ContentApprovalRequest(BaseModel):
    """Human-in-the-loop review and approval decision for a marketing draft."""
    content_id: UUID
    approved: bool
    review_notes: str | None = None
    reviewed_by: UUID


class PublishRequest(BaseModel):
    """Authorized instruction to publish or schedule an approved marketing draft."""
    content_id: UUID
    social_account_id: UUID
    scheduled_at: datetime | None = None
    dry_run: bool = False
